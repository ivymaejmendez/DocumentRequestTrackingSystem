// Process setup form submission
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $inHost = trim($_POST['db_host'] ?? '');
    $inDb   = trim($_POST['db_name'] ?? '');
    $inUser = trim($_POST['db_user'] ?? '');
    $inPass = $_POST['db_pass'] ?? '';

    if ($inHost === '' || $inDb === '' || $inUser === '') {
        $error = 'Please fill in Database Host, Database Name, and Database Username.';
    } else {
        try {
            // 1. Test database connection
            $dsn = "mysql:host=$inHost;dbname=$inDb;charset=utf8mb4";
            $pdo = new PDO($dsn, $inUser, $inPass, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                PDO::MYSQL_ATTR_MULTI_STATEMENTS => true,
            ]);

            // 2. Write config/database.local.php
            $configContent = "<?php\n"
                . "// Automatically generated by setup.php\n"
                . "\$host    = " . var_export($inHost, true) . ";\n"
                . "\$db      = " . var_export($inDb, true) . ";\n"
                . "\$user    = " . var_export($inUser, true) . ";\n"
                . "\$pass    = " . var_export($inPass, true) . ";\n"
                . "\$charset = 'utf8mb4';\n";

            if (!is_dir(__DIR__ . '/config')) {
                mkdir(__DIR__ . '/config', 0755, true);
            }
            file_put_contents($configFile, $configContent);

            // 3. Initialize database tables if not already present
            if (file_exists($sqlFile)) {
                $sql = file_get_contents($sqlFile);
                if (!empty($sql)) {
                    $pdo->exec($sql);
                }
            }

            $alreadyConnected = true;
            $currentHost = $inHost;
            $currentDb   = $inDb;
            $success = "Database connected and initialized successfully!";
        } catch (Throwable $e) {
            $error = 'Connection failed: ' . $e->getMessage();
        }
    }
}
